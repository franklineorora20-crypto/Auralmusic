function sampleArtists(): Artist[] {
  const seen = new Map<string, Artist>();
  for (const track of sampleTracks) {
    const id = track.artistId ?? track.artist;
    if (seen.has(id)) continue;
    seen.set(id, {
      id,
      providerId: "sample",
      providerName: PROVIDER_NAMES.sample,
      providerArtistId: track.artist,
      name: track.artist,
      avatar: "",
      trackCount: sampleTracks.filter((entry) => entry.artist === track.artist).length,
      accent: accentFor(track.artist, 30),
    });
  }
  return [...seen.values()];
}

export const sampleProvider: MusicProvider = {
  id: "sample",
  name: PROVIDER_NAMES.sample,

  isEnabled: () => true,
  disabledReason: () => undefined,

  async searchTracks(query, options: TrackQueryOptions) {
    const term = query.trim().toLowerCase();
    const found = sampleTracks.filter((track) => {
      if (options.genre && !track.genre.toLowerCase().includes(options.genre.toLowerCase())) return false;
      if (!term) return true;
      return `${track.title} ${track.artist} ${track.album} ${track.genre}`.toLowerCase().includes(term);
    });
    const offset = options.offset ?? 0;
    return found.slice(offset, offset + (options.limit ?? 20));
  },

  async searchArtists(query, options: ListOptions) {
    const term = query.trim().toLowerCase();
    return sampleArtists().filter((artist) => !term || artist.name.toLowerCase().includes(term)).slice(0, options.limit ?? 12);
  },

  async searchPlaylists() {
    return [];
  },

  async getTrending(options: TrackQueryOptions) {
    return sampleTracks.slice(options.offset ?? 0, (options.offset ?? 0) + (options.limit ?? 20));
  },

  async getGenreTracks(genre, options: ListOptions) {
    return sampleTracks
      .filter((track) => track.genre.toLowerCase().includes(genre.toLowerCase()))
      .slice(options.offset ?? 0, (options.offset ?? 0) + (options.limit ?? 20));
  },

  async getPopularArtists(options: ListOptions) {
    return sampleArtists().slice(0, options.limit ?? 12);
  },

  async getFeaturedPlaylists() {
    return [];
  },

  async getArtist(artistId) {
    return sampleArtists().find((artist) => artist.id === artistId) ?? null;
  },

  async getArtistTracks(artistId, options: ListOptions) {
    const found = sampleTracks.filter((track) => track.artistId === artistId);
    return found.slice(options.offset ?? 0, (options.offset ?? 0) + (options.limit ?? 25));
  },

  async getPlaylist() {
    return null;
  },

  async getPlaylistTracks() {
    return [];
  },

  async getTrack(trackId) {
    return sampleTracks.find((track) => track.id === trackId || track.providerTrackId === trackId) ?? null;
  },
};
